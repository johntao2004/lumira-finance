    public static List<Cell> preview(
            String template, Map<String, BigDecimal> explicitlyComputedRows) {
        List<Row> definitions = rows().stream().filter(r -> r.template().equals(template)).toList();
        if (definitions.isEmpty()) throw new IllegalArgumentException("RULE_VERSION_UNAVAILABLE");
        Set<String> known = new HashSet<>();
        for (Row row : definitions) known.add(row.id());
        for (var input : explicitlyComputedRows.entrySet())
            if (!known.contains(input.getKey()) || input.getValue() == null)
                throw new IllegalArgumentException(
                        "UNKNOWN_OR_MISSING_REPORT_ROW:" + input.getKey());
        return definitions.stream()
                .map(
                        r ->
                                new Cell(
                                        r.id(),
                                        explicitlyComputedRows.get(r.id()),
                                        explicitlyComputedRows.containsKey(r.id())
                                                ? "DRAFT"
                                                : "MISSING"))
                .toList();
    }

    public static List<String> publicationErrors(String template, List<Cell> cells) {
        List<String> errors = new ArrayList<>();
        errors.add("RULE_PACKAGE_UNREVIEWED:" + template);
        Set<String> ids = new HashSet<>();
        Set<String> known = new HashSet<>();
        for (Row row : rows()) if (row.template().equals(template)) known.add(row.id());
        if (known.isEmpty()) errors.add("RULE_VERSION_UNAVAILABLE");
        for (Cell cell : cells) {
            if (!known.contains(cell.rowId())) errors.add("UNKNOWN_REPORT_ROW:" + cell.rowId());
            if (!ids.add(cell.rowId())) errors.add("DUPLICATE_ROW:" + cell.rowId());
            if (cell.value() == null || "MISSING".equals(cell.status()))
                errors.add("MISSING:" + cell.rowId());
        }
        for (Row row : rows())
            if (row.template().equals(template) && !ids.contains(row.id()))
                errors.add("MISSING:" + row.id());
        return List.copyOf(errors);
    }
